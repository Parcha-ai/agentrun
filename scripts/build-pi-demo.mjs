// The native package ships the same research definition as the repository demo. Written only when it changed, so an
// unchanged demo leaves the Pi package's build current.
import { readFile, writeFile } from 'node:fs/promises';
import { deepResearch } from '../examples/typed-research.ts';
import { question, sourceSets, subquestions } from '../examples/typed-research-fixtures.ts';
const data = { workflow: deepResearch, question, sources: sourceSets.flat(), subquestions, evidenceIds: sourceSets.map(set => set[0].id) };
const target = new URL('../packages/pi/src/demo-data.ts', import.meta.url);
const text = '// Generated by scripts/build-pi-demo.mjs from the public research example.\nexport const demoData = ' + JSON.stringify(data, null, 2) + ';\n';
if (await readFile(target, 'utf8').catch(() => null) !== text) await writeFile(target, text);
