import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { typeOf, typesOf, typesText } from './clients/types.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const GENERATOR = join(ROOT, 'scripts', 'generate-clients.mjs');
const TYPES = join(ROOT, 'apps', 'console', 'src', 'lib', 'api.generated.ts');

test('a schema is the TypeScript type of its shape: types, nulls, enums, consts, objects, maps, lists, unions and refs', () => {
  assert.equal(typeOf({ type: 'string', format: 'date-time' }), 'string');
  assert.equal(typeOf({ type: ['integer', 'null'], minimum: 0 }), 'number | null');
  assert.equal(typeOf({ enum: ['a', 'b', null] }), '"a" | "b" | null');
  assert.equal(typeOf({ const: false }), 'false');
  assert.equal(typeOf({ $ref: '#/components/schemas/RunStatus' }), 'components["RunStatus"]');
  assert.equal(typeOf({ type: 'array', items: { enum: ['x', 'y'] } }), '("x" | "y")[]');
  assert.equal(typeOf({ type: 'array', prefixItems: [{ type: 'string' }, { type: 'number' }], items: false }), '[string, number]');
  assert.equal(typeOf({ type: 'object', additionalProperties: { type: 'boolean' } }), 'Record<string, boolean>');
  assert.equal(typeOf({ type: 'object' }), 'Record<string, unknown>');
  assert.equal(typeOf({}), 'unknown');
  assert.equal(typeOf({ type: 'object', additionalProperties: false, required: ['id'], properties: { id: { type: 'string' }, 'a-b': { type: ['string', 'null'] } } }),
    '{\n  id: string;\n  "a-b"?: string | null;\n}');
  assert.equal(typeOf({ oneOf: [{ $ref: '#/components/schemas/A' }, { type: 'null' }] }), 'components["A"] | null');
  assert.equal(typeOf({ allOf: [{ $ref: '#/components/schemas/A' }, { $ref: '#/components/schemas/B' }] }), 'components["A"] & components["B"]');
  assert.equal(typeOf({ allOf: [{ oneOf: [{ type: 'string' }, { type: 'number' }] }, { $ref: '#/components/schemas/B' }] }), '(string | number) & components["B"]');
  assert.throws(() => typeOf({ $ref: '#/components/responses/NotFound' }), /a \$ref the types cannot follow/);
});

test('the types are made of shapes only: a description, an example or a bound changes neither the file nor its hash', () => {
  const doc = (extra) => ({
    components: { schemas: { Thing: { type: 'object', required: ['n'], properties: { n: { type: 'integer', ...extra } }, ...extra } } },
    paths: { '/things': { get: { operationId: 'listThings', responses: { 200: { description: 'ok', content: { 'application/json': { schema: { $ref: '#/components/schemas/Thing' } } } } } } } },
  });
  const plain = typesOf(doc({}));
  assert.deepEqual(typesOf(doc({ description: 'A thing.', example: 3, minimum: 1, 'x-agentrun-serve': 'thing/1' })), plain);
  const text = typesText(plain, 'h');
  assert.match(text, /^\/\/ Generated by scripts\/generate-clients\.mjs from the server's OpenAPI document\. Do not edit/);
  assert.match(text, /  Thing: \{\n    n: number;\n  \};/);
  assert.match(text, /  listThings: \{\n    body: never;\n    answer: components\["Thing"\];\n  \};/);
});

test("generate-clients --check passes on the committed console types, and fails on a hand-edited one or a document whose shapes moved", { timeout: 120_000 }, async (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'console-types-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const check = (...args) => spawnSync(process.execPath, [GENERATOR, '--check', ...args], { encoding: 'utf8', cwd: ROOT });
  const committed = check();
  assert.equal(committed.status, 0, committed.stderr);

  const edited = join(dir, 'api.generated.ts');
  writeFileSync(edited, readFileSync(TYPES, 'utf8').replace('RunState: "working" | "waiting" | "idle";', 'RunState: string;'));
  const stale = check('--types', edited);
  assert.equal(stale.status, 1);
  assert.match(stale.stderr, /api\.generated\.ts is not the server's document's; run node scripts\/generate-clients\.mjs/);

  const { servedDocument } = await import(GENERATOR);
  const served = await servedDocument();
  const file = join(dir, 'doc.json');
  const described = structuredClone(served);
  described.components.schemas.RunStatus.description = 'Another description.';
  writeFileSync(file, JSON.stringify(described));
  const same = check('--document', file);
  assert.equal(same.status, 0, same.stderr);
  const moved = structuredClone(served);
  moved.components.schemas.RunStatus.enum = [...moved.components.schemas.RunStatus.enum, 'sleeping'];
  writeFileSync(file, JSON.stringify(moved));
  const shape = check('--document', file);
  assert.equal(shape.status, 1);
  assert.match(shape.stderr, /apps\/console\/src\/lib\/api\.generated\.ts (is|are) not the server's document's/);
});
