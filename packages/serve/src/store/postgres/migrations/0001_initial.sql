  record TEXT COLLATE "C" NOT NULL CHECK (record::json IS NOT NULL),
  PRIMARY KEY (run_id, id)
);
CREATE INDEX pi_entries_by_conversation ON pi_entries (run_id, conversation_id, id DESC);
