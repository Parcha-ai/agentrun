-- The store's schema on Postgres, version 1: store/schema.ts's tables (SQLite) in Postgres types. Applied once, by the
-- server, in the store's own schema (search_path), inside the transaction migrate.ts opens; recorded in schema_migrations.
-- Never edit this file once applied: a change is a new file (0002_...), and the server refuses a changed one.
--
-- Mapping: INTEGER -> BIGINT (ms, ids, epochs, counts, and the 0/1 flags the shared code reads as numbers); REAL ->
-- DOUBLE PRECISION; BLOB -> BYTEA (sealed bytes, never opened here); TEXT -> TEXT COLLATE "C" (byte order, as SQLite
-- orders); JSON stays TEXT, checked by a json cast (never jsonb: it reorders keys and refuses some escapes the journal's
-- encoded identities carry). SQLite's rowid tie-break of firings written in the same ms is the identity column `ord`.

CREATE TABLE store_meta (
  singleton BIGINT PRIMARY KEY CHECK (singleton = 1),
  schema_version BIGINT NOT NULL,
  flushes BIGINT NOT NULL DEFAULT 0
);
INSERT INTO store_meta (singleton, schema_version) VALUES (1, 1);

CREATE TABLE agents (
  id TEXT COLLATE "C" PRIMARY KEY,
  name TEXT COLLATE "C" NOT NULL,
  description TEXT COLLATE "C",
  current_revision TEXT COLLATE "C",
  created_at BIGINT NOT NULL,
  archived_at BIGINT
);

CREATE TABLE revisions (
  id TEXT COLLATE "C" PRIMARY KEY,
  agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents (id),
  parent_id TEXT COLLATE "C" REFERENCES revisions (id),
  kind TEXT COLLATE "C" NOT NULL CHECK (kind IN ('agentic', 'workflow')),
  body TEXT COLLATE "C" NOT NULL CHECK (body::json IS NOT NULL),
  skills TEXT COLLATE "C" CHECK (skills IS NULL OR skills::json IS NOT NULL),
  package TEXT COLLATE "C" CHECK (package IS NULL OR package::json IS NOT NULL),
  note TEXT COLLATE "C",
  created_at BIGINT NOT NULL
);
CREATE INDEX revisions_by_agent ON revisions (agent_id, created_at);

CREATE TABLE runs (
  id TEXT COLLATE "C" PRIMARY KEY,
  agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents (id),
  revision_id TEXT COLLATE "C" NOT NULL REFERENCES revisions (id),
  state TEXT COLLATE "C" NOT NULL CHECK (state IN ('queued', 'running', 'parked', 'ended', 'stopped', 'failed')),
  epoch BIGINT NOT NULL DEFAULT 0,
  runner TEXT COLLATE "C",
  claimed_until BIGINT,
  wake_at BIGINT,
  backoff_until BIGINT,
  cost_usd DOUBLE PRECISION,
  metrics TEXT COLLATE "C" CHECK (metrics IS NULL OR metrics::json IS NOT NULL),
  summary TEXT COLLATE "C",
  outcome TEXT COLLATE "C" CHECK (outcome IS NULL OR outcome IN ('completed', 'escalated')),
  archived_at BIGINT,
  imported_from TEXT COLLATE "C" CHECK (imported_from IS NULL OR imported_from::json IS NOT NULL),
  sign_in_handed TEXT COLLATE "C" CHECK (sign_in_handed IS NULL OR sign_in_handed::json IS NOT NULL),
  left_running_at BIGINT,
  started_at BIGINT NOT NULL,
  ended_at BIGINT
);
CREATE INDEX runs_by_agent ON runs (agent_id, started_at);
CREATE INDEX runs_by_revision ON runs (revision_id, started_at);
CREATE INDEX runs_claimable ON runs (state, started_at);
CREATE UNIQUE INDEX runs_import ON runs ((imported_from::json ->> 'source'), (imported_from::json ->> 'session')) WHERE imported_from IS NOT NULL;

CREATE TABLE commands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id TEXT COLLATE "C" NOT NULL REFERENCES runs (id),
  kind TEXT COLLATE "C" NOT NULL,
  body TEXT COLLATE "C" NOT NULL CHECK (body::json IS NOT NULL),
  created_at BIGINT NOT NULL,
  taken_at BIGINT,
  refused TEXT COLLATE "C",
  tries BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX commands_by_run ON commands (run_id, id);
CREATE INDEX commands_untaken ON commands (run_id) WHERE taken_at IS NULL;

CREATE TABLE idempotency (
