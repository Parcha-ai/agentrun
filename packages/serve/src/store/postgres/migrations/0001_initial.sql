CREATE TABLE triggers (
  id TEXT COLLATE "C" PRIMARY KEY,
  agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents (id),
  name TEXT COLLATE "C" NOT NULL,
  enabled BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
  source TEXT COLLATE "C" NOT NULL CHECK (source::json IS NOT NULL),
  target TEXT COLLATE "C" NOT NULL CHECK (target::json IS NOT NULL),
  next_at BIGINT,
  last_run_id TEXT COLLATE "C" REFERENCES runs (id) ON DELETE SET NULL,
  catchup_window_s BIGINT,
  failures_in_a_row BIGINT NOT NULL DEFAULT 0,
  disabled TEXT COLLATE "C" CHECK (disabled IS NULL OR disabled::json IS NOT NULL),
  max_active_runs BIGINT CHECK (max_active_runs IS NULL OR max_active_runs BETWEEN 1 AND 100),
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (agent_id, name)
);
CREATE INDEX triggers_due ON triggers (enabled, next_at);

CREATE TABLE trigger_scopes (
  kind TEXT COLLATE "C" NOT NULL,
  scope TEXT COLLATE "C" NOT NULL,
  trigger_id TEXT COLLATE "C" NOT NULL REFERENCES triggers (id) ON DELETE CASCADE,
  PRIMARY KEY (kind, scope)
);

CREATE TABLE trigger_firings (
  trigger_id TEXT COLLATE "C" NOT NULL REFERENCES triggers (id) ON DELETE CASCADE,
  key TEXT COLLATE "C" NOT NULL,
  by TEXT COLLATE "C",
  nominal_at BIGINT,
  status TEXT COLLATE "C" NOT NULL CHECK (status IN ('due', 'started', 'sent', 'skipped', 'failed', 'missed', 'ignored')),
  at BIGINT NOT NULL,
  run_id TEXT COLLATE "C" REFERENCES runs (id) ON DELETE SET NULL,
  reason TEXT COLLATE "C",
  error TEXT COLLATE "C" CHECK (error IS NULL OR error::json IS NOT NULL),
  count BIGINT,
  attempts BIGINT NOT NULL DEFAULT 0,
  retry_at BIGINT,
  notified BIGINT,
  catch_up BIGINT,
  paused BIGINT,
  payload TEXT COLLATE "C",
  attrs TEXT COLLATE "C" CHECK (attrs IS NULL OR attrs::json IS NOT NULL),
  shown BIGINT,
  waits_on TEXT COLLATE "C",
  ord BIGINT GENERATED ALWAYS AS IDENTITY,
  PRIMARY KEY (trigger_id, key)
);
CREATE INDEX trigger_firings_retry ON trigger_firings (status, retry_at);
CREATE INDEX trigger_firings_recent ON trigger_firings (trigger_id, at DESC);

