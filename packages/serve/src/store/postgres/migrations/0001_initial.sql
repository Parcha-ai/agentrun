  kind TEXT COLLATE "C" NOT NULL,
  status TEXT COLLATE "C" NOT NULL CHECK (status IN ('pending', 'running', 'waiting', 'sleeping', 'completing', 'terminal')),
  abort_requested BIGINT NOT NULL CHECK (abort_requested IN (0, 1)),
  background BIGINT NOT NULL CHECK (background IN (0, 1)),
  seq BIGINT NOT NULL,
  record TEXT COLLATE "C" NOT NULL CHECK (record::json IS NOT NULL),
  PRIMARY KEY (run_id, id)
