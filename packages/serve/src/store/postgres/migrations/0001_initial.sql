CREATE INDEX pi_tasks_by_seq ON pi_tasks (run_id, seq);
CREATE INDEX pi_tasks_by_status ON pi_tasks (run_id, status, id);
CREATE INDEX pi_tasks_by_conversation ON pi_tasks (run_id, conversation_id, id);
