// The Render walk (deploy/render/walk.mjs, the daily walk's render-hosted row), with no Render account: the service it
// makes is render.yaml's, as the button's Blueprint makes it, with the values Render would generate made by the walk.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { parse } from "yaml";

const ROOT = new URL("../../../", import.meta.url);
const { PREFIX, serviceRequest } = await import(new URL("deploy/render/walk.mjs", ROOT));
const blueprint = parse(await readFile(new URL("render.yaml", ROOT), "utf8"));

test("the walk makes render.yaml's service: its image, plan, disk and health check, its variables, the generated ones made", () => {
  const svc = blueprint.services[0];
  const generated = { AGENTRUN_TOKEN: "t".repeat(64), AGENTRUN_SEAL_KEY: "s".repeat(44) };
  const body = serviceRequest(blueprint, { ownerId: "tea-walk", name: `${PREFIX}20261119t0617`, generated });
  assert.equal(body.image.imagePath, svc.image.url);
  assert.deepEqual(
    { plan: body.serviceDetails.plan, health: body.serviceDetails.healthCheckPath, disk: body.serviceDetails.disk },
    { plan: svc.plan, health: svc.healthCheckPath, disk: { name: svc.disk.name, mountPath: svc.disk.mountPath, sizeGB: svc.disk.sizeGB } },
  );
  const env = Object.fromEntries(body.envVars.map((e) => [e.key, e.value]));
  for (const e of svc.envVars) {
    if (e.generateValue) assert.equal(env[e.key], generated[e.key], `${e.key}: generated by the walk, as Render's generateValue`);
    else if (e.value !== undefined) assert.equal(env[e.key], e.value, e.key);
    else assert.equal(e.key in env, false, `${e.key}: left blank, as a person leaves it`);
  }
  assert.equal(env.AGENTRUN_TELEMETRY, "0", "the walk is not a user: no usage counts");
});

test("a walk stopped midway (the job cancelled or out of time: SIGINT, then SIGTERM) deletes what it made, then exits", async () => {
  const { spawn } = await import("node:child_process");
  const { mkdtemp, readFile: read } = await import("node:fs/promises");
  const { tmpdir } = await import("node:os");
  const { join } = await import("node:path");
  const dir = await mkdtemp(join(tmpdir(), "walk-stop-"));
  const walk = new URL("deploy/railway/publish-and-walk.mjs", ROOT).href;
  for (const [signal, code] of [["SIGINT", 130], ["SIGTERM", 143]]) {
    const mark = join(dir, signal);
    // The walk's stand-in: something made, its delete a write, then a wait no walk outlives.
    const script = `const { onStop } = await import(${JSON.stringify(walk)}); const { writeFileSync } = await import("node:fs");
onStop(async () => writeFileSync(${JSON.stringify(mark)}, "deleted")); console.log("made"); setTimeout(() => {}, 60_000);`;
    const child = spawn(process.execPath, ["--input-type=module", "-e", script], { stdio: ["ignore", "pipe", "inherit"] });
    const exited = new Promise((r) => child.once("exit", (c) => r(c)));
    const started = await Promise.race([new Promise((r) => child.stdout.once("data", () => r(true))), exited.then(() => false)]);
    assert.ok(started, `${signal}: the stand-in walk started`);
    child.kill(signal);
    const exit = await exited;
    assert.equal(await read(mark, "utf8"), "deleted", `${signal}: deleted`);
    assert.equal(exit, code, `${signal}: exits ${code}`);
  }
});

test("the walk tries a request again only while Render's edge answers (502, 503 or 504, not JSON), a POST under one Idempotency-Key, within its time", async () => {
  const { throughEdge } = await import("../../../deploy/render/walk.mjs");
  // The edge answers in HTML or nothing; the server always in JSON.
  const edge = (status) => new Response("<html>bad gateway</html>", { status, headers: { "content-type": "text/html" } });
  const server = (status) => new Response(JSON.stringify({ error: { code: "unavailable" } }), { status, headers: { "content-type": "application/json" } });
  const answering = (answers) => {
    const sent = [];
    return { sent, fetch: async (url, init) => { sent.push(init); return answers.shift() ?? new Response("{}", { status: 201, headers: { "content-type": "application/json" } }); } };
  };

  const flaky = answering([edge(502), edge(503), edge(504)]);
  const retried = { n: 0 };
  const created = await throughEdge("https://x.onrender.com/v2/agents/a/runs", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" }, { fetch: flaky.fetch, waitMs: 1, forMs: 1_000, retried });
  assert.equal(created.status, 201);
  assert.equal(retried.n, 3);
  // Each send of the POST carries the same key, so a create the server did make is replayed, not made again.
  const keys = flaky.sent.map((init) => new Headers(init.headers).get("idempotency-key"));
  assert.equal(keys.length, 4);
  assert.ok(keys[0] && keys.every((k) => k === keys[0]), JSON.stringify(keys));
  assert.equal(new Headers(flaky.sent[0].headers).get("content-type"), "application/json", "the caller's headers are kept");

  // The server's own 503 (JSON) and its refusals are its answer: returned at once, never sent again.
  for (const answer of [server(503), server(409)]) {
    const once = answering([answer]);
    assert.equal((await throughEdge("https://x.onrender.com/v2/setup", { method: "POST" }, { fetch: once.fetch, waitMs: 1, forMs: 1_000 })).status, answer.status);
    assert.equal(once.sent.length, 1);
  }

  // An edge that keeps failing: its last answer once the time is up, with no send after the deadline.
  const down = { n: 0, fetch: async () => { down.n++; return edge(502); } };
  let t = Date.now();
  assert.equal((await throughEdge("https://x.onrender.com/", {}, { fetch: down.fetch, waitMs: 5, forMs: 50 })).status, 502);
  assert.ok(Date.now() - t < 1_000);
  assert.ok(down.n <= 11, `${down.n} sends in 50 ms at 5 ms apart`);

  // A request that never answers is cut at the time left, not waited on.
  const hung = (url, init) => new Promise((_, reject) => init.signal.addEventListener("abort", () => reject(init.signal.reason)));
  t = Date.now();
  await assert.rejects(throughEdge("https://x.onrender.com/", {}, { fetch: hung, waitMs: 5, forMs: 100 }));
  assert.ok(Date.now() - t < 1_000, `${Date.now() - t} ms`);
});
