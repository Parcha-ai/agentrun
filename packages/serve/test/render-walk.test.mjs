// The Render walk (deploy/render/walk.mjs, the daily walk's render-hosted row), with no Render account: the service it
// makes is render.yaml's, as the button's Blueprint makes it, with the values Render would generate made by the walk.
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const ROOT = new URL("../../../", import.meta.url);
const { PREFIX, serviceRequest } = await import(new URL("deploy/render/walk.mjs", ROOT));
// A scratch directory of the test's own, removed when it ends.
const scratch = async (t, prefix) => {
  const dir = await mkdtemp(join(tmpdir(), prefix));
  t.after(() => rm(dir, { recursive: true, force: true }));
  return dir;
};
const blueprint = parse(await readFile(new URL("render.yaml", ROOT), "utf8"));

test("the walk makes render.yaml's service: its image, plan, disk and health check, its variables, the generated ones made", () => {
  const svc = blueprint.services[0];
  const generated = { AGENTRUN_TOKEN: "t".repeat(64), AGENTRUN_SEAL_KEY: "s".repeat(44) };
  const body = serviceRequest(blueprint, { ownerId: "tea-walk", name: `${PREFIX}20261119t0617`, generated });
  assert.equal(body.image.imagePath, svc.image.url);
  assert.deepEqual(
    { plan: body.serviceDetails.plan, health: body.serviceDetails.healthCheckPath, disk: body.serviceDetails.disk },
    { plan: svc.plan, health: svc.healthCheckPath, disk: { name: svc.disk.name, mountPath: svc.disk.mountPath, sizeGB: svc.disk.sizeGB } },
  );
  const env = Object.fromEntries(body.envVars.map((e) => [e.key, e.value]));
  for (const e of svc.envVars) {
    if (e.generateValue) assert.equal(env[e.key], generated[e.key], `${e.key}: generated by the walk, as Render's generateValue`);
    else if (e.value !== undefined) assert.equal(env[e.key], e.value, e.key);
    else assert.equal(e.key in env, false, `${e.key}: left blank, as a person leaves it`);
  }
  assert.equal(env.AGENTRUN_TELEMETRY, "0", "the walk is not a user: no usage counts");
});

test("a walk stopped midway (the job cancelled or out of time: SIGINT, then SIGTERM) deletes what it made, then exits", async (t) => {
  const dir = await scratch(t, "walk-stop-");
  const walk = new URL("deploy/railway/publish-and-walk.mjs", ROOT).href;
  for (const [signal, code] of [["SIGINT", 130], ["SIGTERM", 143]]) {
    const mark = join(dir, signal);
    // The walk's stand-in: something made, its delete a write, then a wait no walk outlives.
    const script = `const { onStop } = await import(${JSON.stringify(walk)}); const { writeFileSync } = await import("node:fs");
onStop(async () => writeFileSync(${JSON.stringify(mark)}, "deleted")); console.log("made"); setTimeout(() => {}, 60_000);`;
    const child = spawn(process.execPath, ["--input-type=module", "-e", script], { stdio: ["ignore", "pipe", "inherit"] });
    const exited = new Promise((r) => child.once("exit", (c) => r(c)));
    const started = await Promise.race([new Promise((r) => child.stdout.once("data", () => r(true))), exited.then(() => false)]);
    assert.ok(started, `${signal}: the stand-in walk started`);
    child.kill(signal);
    const exit = await exited;
    assert.equal(await readFile(mark, "utf8"), "deleted", `${signal}: deleted`);
    assert.equal(exit, code, `${signal}: exits ${code}`);
  }
});

test("a walk stopped by SIGINT, then SIGTERM while its delete is still running (Actions' cancel), finishes the delete before it exits, though its finally took the handlers off", async (t) => {
  const mark = join(await scratch(t, "walk-stop-"), "deleted");
  const walk = new URL("deploy/railway/publish-and-walk.mjs", ROOT).href;
  // The stand-in's delete takes 1.5 s. The walk goes on after the SIGINT, and its `finally` calls onStop's off() while
  // that delete runs; then it says "deleting", and the SIGTERM lands in the middle of the delete.
  const script = `const { onStop } = await import(${JSON.stringify(walk)}); const { writeFileSync } = await import("node:fs");
const off = onStop(async () => { setTimeout(() => { off(); console.log("deleting"); }, 0); await new Promise((r) => setTimeout(r, 1500)); writeFileSync(${JSON.stringify(mark)}, "deleted"); });
console.log("made"); setTimeout(() => {}, 60_000);`;
  const child = spawn(process.execPath, ["--input-type=module", "-e", script], { stdio: ["ignore", "pipe", "inherit"] });
  const exited = new Promise((r) => child.once("exit", (code, signal) => r({ code, signal })));
  const said = (word) => Promise.race([new Promise((r) => { const on = (c) => { if (String(c).includes(word)) { child.stdout.off("data", on); r(true); } }; child.stdout.on("data", on); }), exited.then(() => false)]);
  assert.ok(await said("made"), "the stand-in walk started");
  const deleting = said("deleting");
  child.kill("SIGINT");
  assert.ok(await deleting, "the SIGINT started the delete");
  child.kill("SIGTERM");
  const { code, signal } = await exited;
  assert.equal(await readFile(mark, "utf8").catch(() => "not deleted"), "deleted", "the delete finished");
  assert.deepEqual({ code, signal }, { code: 130, signal: null }, "it exits as the first signal says, not killed by the second");
});

test("the first run's wait asks again when the network cuts a read of the run, and fails at once on an answer the server refused", async () => {
  const { firstRunOf, rows } = await import("../../../deploy/railway/publish-and-walk.mjs");
  const json = (status, body) => new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
  const walk = (reads) => {
    const client = {
      sleep: async () => {},
      http: async (url, init) => {
        if (init?.method === "PUT") return new Response(null, { status: 204 });
        if (url.endsWith("/agents")) return json(201, { agent_id: "a1" });
        if (url.endsWith("/runs")) return json(201, { run_id: "r1" });
        const next = reads.shift();
        if (next instanceof Error) throw next;
        return next;
      },
    };
    const step = rows(() => {});
    const times = { clicked: Date.now() };
    return { step, done: firstRunOf(client, { base: "https://walk.test", token: "t", cookie: "s=1", key: "k", model: "m", step, times }) };
  };
  const cut = walk([new TypeError("fetch failed"), Object.assign(new Error("timed out"), { name: "TimeoutError" }), json(200, { status: "running" }), json(200, { status: "completed", cost: { usd: 0.001 }, result: "notes" })]);
  await cut.done;
  assert.equal(cut.step.all.at(-1)[0], "first run finished");
  const refused = walk([json(401, { error: { message: "unauthorized" } })]);
  await assert.rejects(refused.done, /GET \/v2\/runs\/r1 answered 401: unauthorized/);
});

test("the walk tries a request again only while Render's edge answers (502, 503 or 504, not JSON), a POST under one Idempotency-Key, within its time", async () => {
  const { throughEdge } = await import("../../../deploy/render/walk.mjs");
  // The edge answers in HTML or nothing; the server always in JSON.
  const edge = (status) => new Response("<html>bad gateway</html>", { status, headers: { "content-type": "text/html" } });
  const server = (status) => new Response(JSON.stringify({ error: { code: "unavailable" } }), { status, headers: { "content-type": "application/json" } });
  const answering = (answers) => {
    const sent = [];
    return { sent, fetch: async (url, init) => { sent.push(init); return answers.shift() ?? new Response("{}", { status: 201, headers: { "content-type": "application/json" } }); } };
  };

  const flaky = answering([edge(502), edge(503), edge(504)]);
  const retried = { n: 0 };
  const created = await throughEdge("https://x.onrender.com/v2/agents/a/runs", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" }, { fetch: flaky.fetch, waitMs: 1, forMs: 1_000, retried });
  assert.equal(created.status, 201);
  assert.equal(retried.n, 3);
  // Each send of the POST carries the same key, so a create the server did make is replayed, not made again.
  const keys = flaky.sent.map((init) => new Headers(init.headers).get("idempotency-key"));
  assert.equal(keys.length, 4);
  assert.ok(keys[0] && keys.every((k) => k === keys[0]), JSON.stringify(keys));
  assert.equal(new Headers(flaky.sent[0].headers).get("content-type"), "application/json", "the caller's headers are kept");

  // The server's own 503 (JSON) and its refusals are its answer: returned at once, never sent again.
  for (const answer of [server(503), server(409)]) {
    const once = answering([answer]);
    assert.equal((await throughEdge("https://x.onrender.com/v2/setup", { method: "POST" }, { fetch: once.fetch, waitMs: 1, forMs: 1_000 })).status, answer.status);
    assert.equal(once.sent.length, 1);
  }

  // An edge that keeps failing: its last answer once the time is up, with no send after the deadline. One that ignored
  // forMs would hang into the test's own timeout.
  const down = { n: 0, fetch: async () => { down.n++; return edge(502); } };
  assert.equal((await throughEdge("https://x.onrender.com/", {}, { fetch: down.fetch, waitMs: 5, forMs: 50 })).status, 502);
  assert.ok(down.n <= 11, `${down.n} sends in 50 ms at 5 ms apart`);

  // A request that never answers is cut at the time left, not waited on.
  const hung = (url, init) => new Promise((_, reject) => init.signal.addEventListener("abort", () => reject(init.signal.reason)));
  // Each send's timeout is the time left, never more: read from what it asks of AbortSignal.timeout, not from a clock.
  const timeout = AbortSignal.timeout;
  const asked = [];
  AbortSignal.timeout = (ms) => (asked.push(ms), timeout.call(AbortSignal, ms));
  try {
    await assert.rejects(throughEdge("https://x.onrender.com/", {}, { fetch: hung, waitMs: 5, forMs: 100 }));
  } finally {
    AbortSignal.timeout = timeout;
  }
  assert.equal(asked.length, 1, "one send, cut at the deadline");
  assert.ok(asked[0] >= 1 && asked[0] <= 100, `the send's timeout is ${asked[0]} ms, not the 100 ms left or less`);
});

test("render.yaml's image not published: the walk makes no service, and its report says why", async (t) => {
  const dir = await scratch(t, "walk-image-");
  const log = join(dir, "requests.jsonl");
  // Render's API with one workspace and no services left, GHCR with no such tag; every request is written down.
  const stub = join(dir, "stub.mjs");
  await writeFile(stub, `import { appendFileSync } from "node:fs";
globalThis.fetch = async (url, init = {}) => {
  url = String(url);
  appendFileSync(${JSON.stringify(log)}, JSON.stringify({ method: init.method ?? "GET", url }) + "\\n");
  if (url.startsWith("https://api.render.com/v1/owners")) return Response.json([{ owner: { id: "tea-walk", name: "Walks" } }]);
  if (url.startsWith("https://api.render.com/v1/services?")) return Response.json([]);
  if (url.startsWith("https://ghcr.io/token?")) return Response.json({ token: "anon" });
  if (url.startsWith("https://ghcr.io/v2/")) return new Response(null, { status: 404 });
  return new Response("unexpected", { status: 500 });
};
`);
  const report = join(dir, "report.md");
  const walk = fileURLToPath(new URL("deploy/render/walk.mjs", ROOT));
  const child = spawn(process.execPath, ["--import", stub, walk, "--owner", "Walks"], { env: { ...process.env, RENDER_API_KEY: "fake-test-key", OPENROUTER_API_KEY: "fake-test-key", REPORT: report }, stdio: "ignore" });
  const code = await new Promise((resolve) => child.on("exit", resolve));
  assert.equal(code, 1);
  const sent = (await readFile(log, "utf8")).trim().split("\n").map((l) => JSON.parse(l));
  assert.deepEqual(sent.filter((r) => r.method !== "GET" && r.method !== "HEAD"), [], "no service made, nothing deleted");
  assert.ok(sent.some((r) => r.method === "HEAD" && r.url.startsWith("https://ghcr.io/v2/parcha-ai/agentrun-server/manifests/")), "render.yaml's image asked of GHCR");
  const text = await readFile(report, "utf8");
  assert.match(text, /FAIL/);
  assert.match(text, /is not on GHCR yet: nothing made/);
  assert.doesNotMatch(text, /render cost|service deleted/, "nothing made: nothing to delete or bill");
});
