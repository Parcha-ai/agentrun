// An imported run's title: the source's own (Claude Code's custom-title, ai-title or summary record), else the person's
// first words, else where the session ran. Never a CLI's slash-command markup, its output or its preamble, which real
// sessions open with (/clear, /model, /init, /resume).
import assert from "node:assert/strict";
import { mkdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { openStore } from "@parcha/pi-durable-agent";
import { planImport, runImport } from "../dist/import.js";
import * as sources from "../dist/import-sources.js";
import { at, codexSession, piSession, sessionId, writeSession } from "./fixtures/import-sessions.mjs";
import { scratch } from "./support.mjs";

const ENV = { PATH: "/usr/bin" };
// What Claude Code writes for a slash command, as its session files hold it.
const command = (name, args = "") => `<command-name>/${name}</command-name>\n            <command-message>${name}</command-message>\n            <command-args>${args}</command-args>`;
const stdout = (text) => `<local-command-stdout>${text}</local-command-stdout>`;
const CAVEAT = "Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.";
const TITLES = new Set(["custom-title", "ai-title", "summary"]);

/** A Claude Code session in `project`: its `opening` records, then the model's answer (uuid `a<n>`). A string is a user
 *  message of the person's; a title record is written as Claude Code writes it; any other object is a record's fields. */
function claude(home, project, n, opening) {
  const base = { sessionId: sessionId(n), cwd: project, isSidechain: false, userType: "external", version: "2.1.0" };
  let k = 0;
  const records = opening.map((r) => {
    if (typeof r === "object" && TITLES.has(r.type)) return r.type === "summary" ? r : { ...r, sessionId: sessionId(n) };
    k += 1;
    return typeof r === "string" ? { ...base, type: "user", uuid: `u${n}-${k}`, timestamp: at(k), message: { role: "user", content: r } } : { ...base, uuid: `u${n}-${k}`, timestamp: at(k), ...r };
  });
  records.push({ ...base, type: "assistant", uuid: `a${n}`, timestamp: at(k + 1), message: { id: `msg_${n}`, role: "assistant", model: "claude-sonnet-5", content: [{ type: "text", text: "Done." }], usage: { input_tokens: 10, output_tokens: 2 } } });
  return writeSession(join(home, ".claude", "projects", project.replaceAll("/", "-"), `${sessionId(n)}.jsonl`), records);
}
const meta = (content) => ({ type: "user", isMeta: true, message: { role: "user", content } });

/** Each imported run's title (its serve.json's), by its session's id, for the sessions `write` puts in a home's
 *  billing-api folder, imported with `extra` options. */
async function titles(t, write, extra = {}) {
  const root = await scratch(t);
  const home = join(root, "home");
  const project = join(home, "code", "billing-api");
  mkdirSync(project, { recursive: true });
  write(home, project);
  const data = join(root, "agents");
  const store = openStore(data);
  t.after(() => store.close());
  const options = { home, env: ENV, temp: join(root, "tmp"), ...extra };
  await runImport(store, await planImport(options), options);
  return Object.fromEntries(store.listRuns().map((run) => [run.importedFrom.session, JSON.parse(readFileSync(join(data, "runs", run.id, "serve.json"), "utf8")).title]));
}

test("a Claude Code session that opens with a slash command is titled by the person's first words, never the command's markup", async (t) => {
  const got = await titles(t, (home, project) => {
    claude(home, project, 1, [command("clear"), stdout(""), "Fix the login redirect loop."]);
    claude(home, project, 2, [meta(CAVEAT), command("model", "opus"), stdout("Set model to opus (claude-opus-5)"), "Why is the nightly build slow?"]);
    claude(home, project, 3, [`${command("resume")}\n${stdout("Resumed.")}`, "Carry on with the migration."]);
    claude(home, project, 4, [command("init"), meta("Please analyze this codebase and create a CLAUDE.md file."), "Keep it short."]);
  });
  assert.deepEqual(got, { [sessionId(1)]: "Fix the login redirect loop.", [sessionId(2)]: "Why is the nightly build slow?", [sessionId(3)]: "Carry on with the migration.", [sessionId(4)]: "Keep it short." });
});

test("Claude Code's own title is the run's: the person's rename over its generated one, the latest of each, and a summary only when it titles this session", async (t) => {
  const got = await titles(t, (home, project) => {
    // Current Claude Code: an ai-title, written again as the session goes on.
    claude(home, project, 5, [command("model"), stdout("Kept model as sonnet"), { type: "ai-title", aiTitle: "Model check" }, "Draft the onboarding guide.", { type: "ai-title", aiTitle: "Onboarding guide draft" }]);
    // The person's /rename (custom-title) wins over an ai-title written after it.
    claude(home, project, 6, [{ type: "custom-title", customTitle: "Q4 invoices" }, "Export the invoices.", { type: "ai-title", aiTitle: "Invoice export" }]);
    // Older files: a summary names its conversation's last message; one of this session's is its title.
    claude(home, project, 7, [{ type: "summary", summary: "Retry logic for webhooks", leafUuid: "a7" }, command("init"), "Add retries to the webhook sender."]);
    // A summary of another conversation (its last message is in no record here) is not this session's title.
    claude(home, project, 8, [{ type: "summary", summary: "Some earlier conversation", leafUuid: "elsewhere" }, "Rotate the staging certificate."]);
  });
  assert.deepEqual(got, { [sessionId(5)]: "Onboarding guide draft", [sessionId(6)]: "Q4 invoices", [sessionId(7)]: "Retry logic for webhooks", [sessionId(8)]: "Rotate the staging certificate." });
});

test("a session with no words of the person's is titled by where it ran, on every source", async (t) => {
  const got = await titles(
    t,
    (home, project) => {
      claude(home, project, 9, [command("resume"), stdout(""), command("model"), stdout("Kept model as sonnet")]);
      // Codex: a user message the CLI wrote whole (its environment block, with no user_message event) is no prompt.
      codexSession(home, project, 10, { prompt: `<environment_context>\n  <cwd>${project}</cwd>\n</environment_context>`, events: false });
      piSession(home, project, 11, { prompt: "" });
    },
    // --all: an import keeps a session with no message of the person's only when asked to.
    { all: true },
  );
  assert.deepEqual(got, { [sessionId(9)]: "Session in billing-api", [sessionId(10)]: "Session in billing-api", [sessionId(11)]: "Session in billing-api" });
});

test("personsWords keeps the person's words around a command and drops only the CLI's elements", () => {
  const { personsWords } = sources;
  assert.equal(personsWords(`${command("model")} then fix the test`), "then fix the test");
  assert.equal(personsWords(stdout("ok")), undefined);
  assert.equal(personsWords(CAVEAT), undefined);
  assert.equal(personsWords("<thinking>is mine</thinking>"), "<thinking>is mine</thinking>");
  assert.equal(personsWords("  Rotate   the\n keys.  "), "Rotate the keys.");
});
