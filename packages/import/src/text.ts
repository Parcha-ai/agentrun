export const isObject = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);
export const str = (value: unknown): string | undefined => (typeof value === "string" && value !== "" ? value : undefined);
/** The latest (and, negated, earliest) time a Date holds, in ms from the epoch: a number past it is no time. */
const DATE_RANGE = 8.64e15;
/** A record's time in ms: a number as it is, a string as Date.parse reads it; undefined for none a Date holds. */
export const timeOf = (value: unknown): number | undefined => {
  const at = typeof value === "number" ? value : typeof value === "string" ? (isoTime(value) ?? Date.parse(value)) : Number.NaN;
  return Number.isFinite(at) && Math.abs(at) <= DATE_RANGE ? at : undefined;
};

/** The digits of `s` from `from` to `to` as a number, -1 when one is not a digit. */
function digits(s: string, from: number, to: number): number {
  let n = 0;
  for (let i = from; i < to; i += 1) {
    const d = s.charCodeAt(i) - 48;
    if (d < 0 || d > 9) return -1;
    n = n * 10 + d;
  }
  return n;
}

/** A time written as every record writes one, "YYYY-MM-DDTHH:MM:SS.sssZ", without Date.parse: what it gives for it.
 *  Anything else, a day past the 28th (whether the month has it is Date.parse's to say) and a year under 100, is
 *  undefined. */
function isoTime(s: string): number | undefined {
  if (s.length !== 24 || s.charCodeAt(4) !== 45 || s.charCodeAt(7) !== 45 || s.charCodeAt(10) !== 84 || s.charCodeAt(13) !== 58 || s.charCodeAt(16) !== 58 || s.charCodeAt(19) !== 46 || s.charCodeAt(23) !== 90) return undefined;
  const year = digits(s, 0, 4);
  const month = digits(s, 5, 7);
  const day = digits(s, 8, 10);
  const hour = digits(s, 11, 13);
  const minute = digits(s, 14, 16);
  const second = digits(s, 17, 19);
  const ms = digits(s, 20, 23);
  // Date.UTC takes a year under 100 for 1900 and more.
  if (year < 100 || month < 1 || month > 12 || day < 1 || day > 28 || hour < 0 || hour > 23 || minute < 0 || minute > 59 || second < 0 || second > 59 || ms < 0) return undefined;
  return Date.UTC(year, month - 1, day, hour, minute, second, ms);
}
/** Text from a string or a list of blocks; a block that is not text says what it was. */
export const textOf = (value: unknown): string => {
  if (typeof value === "string") return value;
  if (!Array.isArray(value)) return isObject(value) && typeof value.text === "string" ? value.text : "";
  return value
    .map((block) => (typeof block === "string" ? block : isObject(block) ? (typeof block.text === "string" ? block.text : block.type === "image" || block.type === "input_image" ? "[image]" : textOf(block.content)) : ""))
    .filter(Boolean)
    .join("\n");
};
export const effortOf = (value: unknown): string | undefined => (typeof value === "string" && /^[\w-]{1,32}$/.test(value) ? value : undefined);

export const argsOf = (value: unknown): Record<string, unknown> => {
  if (isObject(value)) return value;
  if (typeof value === "string") {
    try {
      const parsed = JSON.parse(value) as unknown;
      if (isObject(parsed)) return parsed;
    } catch {
      // Not JSON: kept as the tool's one input.
    }
    return { input: value };
  }
  return {};
};

export const INTERRUPTED = /^\[Request interrupted by user/;
// What Claude Code writes into a user message for the person's slash command (/clear, /model, /init, /resume …): the
// command's name, message and arguments, each in its own element, then its output and the preamble it puts before a
// local command's output. Only these elements, whole: a prompt the person wrote around them is theirs.
const CLI_ELEMENT = /<(command-name|command-message|command-args|local-command-stdout|local-command-stderr)>[\s\S]*?<\/\1>/g;
const CLI_PREAMBLE = /^Caveat: The messages below were generated by the user while running local commands\b/;
/** The person's own words in a user message's text, as they wrote them (spaces and lines kept, so a cut still matches
 *  a secret in them): none when the CLI wrote all of it (a slash command, its output, its preamble), or when there are
 *  no words at all. */
export function personsWords(text: string): string | undefined {
  const words = text.replace(CLI_ELEMENT, " ").trim();
  const line = words.replace(/\s+/g, " ");
  return line && !CLI_PREAMBLE.test(line) && !INTERRUPTED.test(line) ? words : undefined;
}

/** The effort most of `turns`' requests ran at, as the model of most requests is a run's model: the first seen of a tie. */
export function mostEffortOf(turns: readonly Turn[]): string | undefined {
  const efforts = new Map<string, number>();
  for (const turn of turns) if (turn.role === "assistant" && turn.effort) efforts.set(turn.effort, (efforts.get(turn.effort) ?? 0) + 1);
  let most: string | undefined;
  for (const [effort, n] of efforts) if (most === undefined || n > efforts.get(most)!) most = effort;
  return most;
}
