"""Exercise generated configuration with an externally supplied OSS Collector."""

import json
import os
from pathlib import Path
import socket
import subprocess
import sys
import tempfile
import threading
import time
import unittest
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from test_cli_process import Peer


@unittest.skipUnless(os.environ.get("AGENTRUN_TEST_COLLECTOR"), "set AGENTRUN_TEST_COLLECTOR to an otelcol-contrib binary")
class CollectorWireTests(unittest.TestCase):
    def test_native_usage_is_cache_inclusive_and_private_fields_never_leave_collector(self):
        peer = Peer()
        self.addCleanup(peer.server.server_close)
        self.addCleanup(peer.server.shutdown)
        received = []
        arrived = threading.Event()

        class Sink(BaseHTTPRequestHandler):
            def do_POST(self):
                received.append(json.loads(self.rfile.read(int(self.headers["Content-Length"]))))
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(b"{}")
                arrived.set()

            def log_message(self, *args):
                pass

        sink = ThreadingHTTPServer(("127.0.0.1", 0), Sink)
        threading.Thread(target=sink.serve_forever, daemon=True).start()
        self.addCleanup(sink.server_close)
        self.addCleanup(sink.shutdown)
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary)
            environment = {**os.environ, "PYTHONPATH": str(Path(__file__).resolve().parents[1] / "src"),
                           "ENROLLMENT_KEY": "private-test-enrollment"}
            connected = subprocess.run([
                sys.executable, "-m", "agentrun_cli", "connect", "--telemetry", "--state-dir", str(directory / "state"),
                "--origin", peer.origin, "--workspace-id", "personal:test", "--subscribe-harness", "claude",
                "--subscribe-harness", "codex", "--credential-env", "ENROLLMENT_KEY", "--yes",
            ], env=environment, capture_output=True, text=True, timeout=15)
            self.assertEqual(connected.returncode, 0, connected.stderr)
            bundle = json.loads(connected.stdout)["telemetry"]
            self.assertEqual(bundle["token_usage_harnesses"], ["claude", "codex"])
            config_path = Path(bundle["config_path"])
            config = json.loads(config_path.read_text())
            ports = {}
            for harness in ["claude", "codex"]:
                with socket.socket() as port_socket:
                    port_socket.bind(("127.0.0.1", 0))
                    ports[harness] = port_socket.getsockname()[1]
                config["receivers"]["otlp/agentrun_" + harness]["protocols"]["http"]["endpoint"] = "127.0.0.1:" + str(ports[harness])
            # Only redirect transport: all privacy and normalization processors remain generated by the CLI.
            config["exporters"]["otlphttp/agentrun"]["logs_endpoint"] = f"http://127.0.0.1:{sink.server_port}/logs"
            config_path.write_text(json.dumps(config))
            environment.update(AGENTRUN_CONNECTOR_CREDENTIAL="narrow-connector-test",
                               AGENTRUN_OTEL_QUEUE_DIRECTORY=str(directory / "state/telemetry/queue"))
            with (directory / "collector.log").open("w+") as collector_log:
                process = subprocess.Popen([os.environ["AGENTRUN_TEST_COLLECTOR"], "--config", str(config_path)],
                                           env=environment, stdout=collector_log, stderr=subprocess.STDOUT)
                try:
                    deadline = time.monotonic() + 15
                    for port in ports.values():
                        while True:
                            self.assertIsNone(process.poll(), "Collector failed to start")
                            try:
                                with socket.create_connection(("127.0.0.1", port), timeout=.2):
                                    break
                            except OSError:
                                self.assertLess(time.monotonic(), deadline, "Collector startup timed out")
                                time.sleep(.05)
                    fixtures = self.native_fixtures()
                    for harness, rows in fixtures.items():
                        records = []
                        for index, attributes in enumerate(rows):
                            native_id = "session.id" if harness == "claude" else "conversation.id"
                            attributes = {**attributes, native_id: "PRIVATE-native-" + harness,
                                          "user.email": "PRIVATE-EMAIL", "tool.output": "PRIVATE-TOOL",
                                          "agentrun.provider": "PRIVATE-CANONICAL", "agentrun.model": "PRIVATE-INJECTED",
                                          "cost_usd": "PRIVATE-COST"}
                            records.append({"timeUnixNano": str(1793400000000000000 + index),
                                            "traceId": "a" * 32, "spanId": "b" * 16,
                                            "body": {"stringValue": "PRIVATE-BODY"}, "attributes": [
                                                {"key": key, "value": {"intValue": str(value)} if isinstance(value, int)
                                                 else {"stringValue": value}} for key, value in attributes.items()]})
                        payload = {"resourceLogs": [{"resource": {"attributes": [
                            {"key": "private.resource", "value": {"stringValue": "PRIVATE-RESOURCE"}}]},
                            "scopeLogs": [{"scope": {"name": "PRIVATE-SCOPE"}, "logRecords": records}]}]}
                        request = urllib.request.Request(f"http://127.0.0.1:{ports[harness]}/v1/logs",
                                                         data=json.dumps(payload).encode(),
                                                         headers={"Content-Type": "application/json"})
                        with urllib.request.urlopen(request, timeout=5) as response:
                            self.assertEqual(response.status, 200)
                    deadline = time.monotonic() + 10
                    while len(received) < 2 and time.monotonic() < deadline:
                        arrived.wait(.2)
                        arrived.clear()
                    by_harness = {}
                    for batch in received:
                        for resource in batch["resourceLogs"]:
                            harness = next(attribute["value"]["stringValue"] for attribute in resource["resource"]["attributes"]
                                           if attribute["key"] == "agentrun.harness")
                            for scope in resource["scopeLogs"]:
                                by_harness.setdefault(harness, []).extend({
                                    attribute["key"]: next(iter(attribute["value"].values()))
                                    for attribute in record["attributes"]} for record in scope["logRecords"])
                    self.assertNotIn("PRIVATE-", json.dumps(received))
                    claude, codex = by_harness.get("claude", []), by_harness.get("codex", [])
                    self.assertEqual(len(claude), 9)
                    self.assertEqual(len(codex), 2)  # Non-completion streaming events are excluded.
                    self.assertEqual([claude[0][name] for name in ["agentrun.input_tokens", "agentrun.output_tokens",
                                                                 "agentrun.cache_read_tokens", "agentrun.cache_write_tokens"]],
                                     ["60", "5", "40", "3"])
                    self.assertEqual(claude[1]["agentrun.input_tokens"], "13")
                    self.assertEqual(claude[1]["agentrun.output_tokens"], "2")
                    for row in claude[2:]:
                        self.assertEqual(set(row), {"agentrun.session_id", "event.name"})
                    self.assertEqual(codex[0]["event.name"], "codex.response_usage")
                    self.assertEqual(codex[0]["agentrun.input_tokens"], "80")
                    self.assertEqual(codex[0]["agentrun.output_tokens"], "9")
                    self.assertEqual(codex[1]["agentrun.input_tokens"], "3")
                    self.assertNotIn("agentrun.cache_read_tokens", codex[1])
                    self.assertNotIn("agentrun.cache_write_tokens", codex[1])
                finally:
                    process.terminate()
                    process.wait(timeout=10)

    @staticmethod
    def native_fixtures():
        claude = {"event.name": "api_request", "model": "claude-test", "input_tokens": 17,
                  "output_tokens": 5, "cache_read_tokens": 40, "cache_creation_tokens": 3}
        codex = {"event.name": "codex.sse_event", "event.kind": "response.completed", "model": "gpt-test",
                 "input_token_count": "80", "output_token_count": "9", "cached_token_count": 60, "cache_write_token_count": 0}
        missing_cache = {key: value for key, value in claude.items() if key != "cache_creation_tokens"}
        return {"claude": [claude,
                           {**claude, "input_tokens": "13", "output_tokens": "2", "cache_read_tokens": "0", "cache_creation_tokens": "0"},
                           {**claude, "model": "PRIVATE-BAD MODEL"}, {**claude, "input_tokens": "PRIVATE-COUNT"},
                           {**claude, "input_tokens": -3}, {**claude, "output_tokens": 9007199254740992}, missing_cache,
                           {**claude, "input_tokens": 9007199254740991, "output_tokens": 1, "cache_read_tokens": 0, "cache_creation_tokens": 0},
                           {**claude, "event.name": "tool_result"}],
                "codex": [codex,
                          {"event.name": "codex.sse_event", "event.kind": "response.completed", "model": "gpt-test",
                           "input_token_count": "3", "output_token_count": "2"},
                          {**codex, "event.kind": "response.output_text.delta"}]}
